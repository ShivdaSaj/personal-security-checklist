// Generates a self-contained docker-compose file for a Docker host (e.g. Hostinger VPS Docker
// Manager) that needs no registry and no git access to this branch:
//   * the app code (src/, build.mjs, package files) is embedded as a base64 tar.gz config,
//   * a one-shot `builder` container fetches the checklist YAML + icons from a public repo
//     (CONTENT_REPO, default the upstream fork's master), builds the site into a volume,
//   * an unprivileged nginx serves it behind Traefik.
// Usage: DOMAIN=checklist.example.com node make-compose.mjs > ../deploy/docker-compose.hostinger.yml
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import os from 'node:os';

const here = path.dirname(fileURLToPath(import.meta.url));
const domain = process.env.DOMAIN || 'checklist.example.com';
const router = process.env.ROUTER || 'defense-console';
const resolver = process.env.CERT_RESOLVER || 'letsencrypt';
const contentRepo = process.env.CONTENT_REPO || 'https://raw.githubusercontent.com/ShivdaSaj/personal-security-checklist/master';

// Minify into a staging dir, then pack as tar.xz to keep the compose file small.
const stage = fs.mkdtempSync(path.join(os.tmpdir(), 'dc-bundle-'));
fs.mkdirSync(path.join(stage, 'src'));
const esbuild = (src, dst, extra = []) => execFileSync('npx', ['--yes', 'esbuild@0.24.0', path.join(here, src), '--minify', '--log-level=warning', `--outfile=${path.join(stage, dst)}`, ...extra]);
esbuild('src/app.js', 'src/app.js');
esbuild('src/styles.css', 'src/styles.css');
esbuild('build.mjs', 'build.mjs', ['--format=esm']);
for (const f of ['src/index.html', 'src/favicon.svg', 'package.json', 'package-lock.json']) fs.copyFileSync(path.join(here, f), path.join(stage, f));
const tarball = execFileSync('tar', ['--sort=name', '--owner=0', '--group=0', '--mtime=@0', '-cJ', 'package.json', 'package-lock.json', 'build.mjs', 'src'], { cwd: stage, env: { ...process.env, XZ_OPT: '-9e' } });
fs.rmSync(stage, { recursive: true, force: true });
const sha = createHash('sha256').update(tarball).digest('hex');
const bundle = tarball.toString('base64').replace(/(.{76})/g, '$1\n');
const indent = (text, n) => text.replace(/\n$/, '').split('\n').map((l) => ' '.repeat(n) + l).join('\n');
// Compose interpolates $VAR, so literal dollars must be doubled.
const nginx = fs.readFileSync(path.join(here, 'nginx.conf'), 'utf8').replace(/\$/g, '$$$$');

const build = [
  'set -e',
  'mkdir -p /work/dashboard /work/web/src/components/core',
  'cd /work/dashboard',
  'base64 -d /bundle.b64 > /tmp/bundle.txz',
  `echo "${sha}  /tmp/bundle.txz" | sha256sum -c -`,
  'tar xJf /tmp/bundle.txz',
  'npm ci --omit=dev --no-audit --no-fund --loglevel=error',
  'wget -qO /work/personal-security-checklist.yml "$$CONTENT_REPO/personal-security-checklist.yml"',
  'wget -qO /work/web/src/components/core/icon.tsx "$$CONTENT_REPO/web/src/components/core/icon.tsx" || true',
  'node build.mjs',
  'rm -rf /out/* && cp -r dist/. /out/ && chmod -R a+rX /out',
].join('\n');

process.stdout.write(`# Generated by dashboard/make-compose.mjs. Edit the generator, not this file.
services:
  builder:
    image: node:22-alpine
    restart: "no"
    environment:
      CONTENT_REPO: ${contentRepo}
    entrypoint: ["/bin/sh", "-c"]
    command:
      - |
${indent(`{\n${indent(build, 2)}\n} || test -f /out/index.html`, 8)}
    configs:
      - source: app_bundle
        target: /bundle.b64
    volumes:
      - site:/out

  defense-console:
    image: nginxinc/nginx-unprivileged:1.27-alpine
    restart: unless-stopped
    depends_on:
      builder:
        condition: service_completed_successfully
    read_only: true
    tmpfs:
      - /tmp
    security_opt:
      - no-new-privileges:true
    cap_drop:
      - ALL
    expose:
      - "8080"
    volumes:
      - site:/usr/share/nginx/html:ro
    configs:
      - source: nginx_conf
        target: /etc/nginx/conf.d/default.conf
    healthcheck:
      test: ["CMD", "wget", "-qO-", "http://127.0.0.1:8080/healthz"]
      interval: 30s
      timeout: 3s
    labels:
      - traefik.enable=true
      - traefik.http.routers.${router}.rule=Host(\`${domain}\`)
      - traefik.http.routers.${router}.entrypoints=websecure
      - traefik.http.routers.${router}.tls=true
      - traefik.http.routers.${router}.tls.certresolver=${resolver}
      - traefik.http.services.${router}.loadbalancer.server.port=8080

volumes:
  site:

configs:
  nginx_conf:
    content: |
${indent(nginx, 6)}
  app_bundle:
    content: |
${indent(bundle, 6)}
`);
